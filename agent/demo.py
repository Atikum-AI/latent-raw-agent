"""Make small generated stand-in clips so the whole agent runs before the real samples land.

    python -m agent.demo                 # writes samples_demo/
    SAMPLES_DIR=samples_demo python run.py --all

Every frame here is generated by this script (flat bands of colour), so there is no
footage rights question. They mirror the eval cases: the same clip ids and item labels,
with the clipped items clipped. The jungle clip comes out of expand one stop hot,
and its balance pass brings it back, so the match check has something to fix.
"""
import json
import sys
from pathlib import Path

import numpy as np
import OpenEXR
from PIL import Image

from measure import metrics

# clip id -> list of (item, 8-bit RGB, clipped?) bands, plus exposure gains
CLIPS = {
    "clip01_car_street_sun": {"bands": [("sky", (255, 255, 255)), ("buildings", (120, 110, 100)),
                                        ("car", (150, 30, 30)), ("road", (200, 198, 190))]},
    "clip02_lantern_table": {"bands": [("lantern_flame", (255, 250, 200)), ("girl", (200, 150, 120)),
                                       ("hands", (190, 140, 110)), ("table", (90, 60, 40))]},
    "clip03a_canoe_dawn": {"bands": [("sky", (170, 190, 230)), ("person_young", (180, 140, 120)),
                                     ("person_old", (160, 120, 100)), ("water", (60, 80, 110))],
                           "expand_gain": 1.0, "balance_gain": 1.0},
    "clip03b_jungle_warm": {"bands": [("sky", (170, 190, 230)), ("person_young", (180, 140, 120)),
                                      ("person_old", (160, 120, 100)), ("forest", (60, 120, 50))],
                            "expand_gain": 2.0, "balance_gain": 0.53},
}
H, W = 40, 80


def _write_exr(path, rgb):
    # Half float, like Kyo's ACEScg passes.
    with OpenEXR.File({"compression": OpenEXR.ZIP_COMPRESSION}, {"RGB": rgb.astype(np.float16)}) as f:
        f.write(str(path))


def make(root="samples_demo"):
    root = Path(root)
    for clip, spec in CLIPS.items():
        d = root / clip
        (d / "masks").mkdir(parents=True, exist_ok=True)
        src = np.zeros((H, W, 3), np.uint8)
        synth = np.zeros((H, W), np.uint8)
        band = H // len(spec["bands"])
        for i, (item, rgb) in enumerate(spec["bands"]):
            m = np.zeros((H, W), np.uint8)
            m[i * band:(i + 1) * band] = 255
            src[m > 0] = rgb
            Image.fromarray(m).save(d / "masks" / f"{item}.png")
            if max(rgb) >= 250:
                synth[m > 0] = 255
        Image.fromarray(src).save(d / "source.png")
        Image.fromarray(synth).save(d / "synth.png")
        lin = metrics.srgb_to_linear(src.astype(np.float32) / 255) * spec.get("expand_gain", 1.0)
        lin[synth > 0] *= 4.0  # the expand pass synthesizes range above 8-bit white
        _write_exr(d / "expand_hdr.exr", lin)
        _write_exr(d / "balance.exr", lin * spec.get("balance_gain", 1.0))
        (d / "clip.json").write_text(json.dumps({"key_frame": 48, "aces": "AP1",
                                                 "source_model": "generated by agent/demo.py"}))
    return root


if __name__ == "__main__":
    print("wrote", make(*sys.argv[1:]))
